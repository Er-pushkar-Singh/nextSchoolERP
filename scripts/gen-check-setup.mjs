// Builds supabase/check_setup.sql: a read-only script that lists every table, column and function the migrations create
// but the connected database does not have — i.e. which migration was not applied (or applied only halfway).
// usage: node scripts/gen-check-setup.mjs
import fs from "node:fs";
import path from "node:path";

const dir = "supabase/migrations";
const files = fs.readdirSync(dir).filter((f) => /^\d{4}_.*\.sql$/.test(f)).sort();
const rows = [];
const dropped = new Set();
for (const f of files) for (const m of fs.readFileSync(path.join(dir, f), "utf8").replace(/--.*$/gm, "").matchAll(/drop\s+(?:function|table)\s+(?:if\s+exists\s+)?public\.([a-z_0-9]+)/gi)) dropped.add(m[1].toLowerCase());
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

for (const f of files) {
  const mig = f.slice(0, 4);
  const sql = fs.readFileSync(path.join(dir, f), "utf8").replace(/--.*$/gm, "");
  const seen = new Set();
  const add = (kind, name, extra = "") => { if (dropped.has(name) && kind !== "column") return; const k = `${kind}|${name}|${extra}`; if (!seen.has(k)) { seen.add(k); rows.push([mig, kind, name, extra]); } };
  for (const m of sql.matchAll(/create\s+table\s+(?:if\s+not\s+exists\s+)?public\.([a-z_0-9]+)/gi)) add("table", m[1].toLowerCase());
  for (const m of sql.matchAll(/create\s+(?:or\s+replace\s+)?function\s+public\.([a-z_0-9]+)\s*\(/gi)) add("function", m[1].toLowerCase());
  for (const m of sql.matchAll(/alter\s+table\s+(?:if\s+exists\s+)?public\.([a-z_0-9]+)\s+add\s+column\s+if\s+not\s+exists\s+([a-z_0-9]+)/gi)) add("column", m[1].toLowerCase(), m[2].toLowerCase());
}

const out = `-- ═══════════════════════════════════════════════════════════════════════════
-- CHECK SETUP — which migrations are missing in this database?  (generated by scripts/gen-check-setup.mjs — do not edit)
-- Run in the Supabase SQL editor. It only reads. Every row returned is something the app expects but the database does not have;
-- apply the listed migration(s) (or re-run supabase/setup.sql) and run this again until it returns "Everything is in place".
-- ═══════════════════════════════════════════════════════════════════════════
with expected(mig, kind, name, extra) as (values
${rows.map((r) => `  (${r.map(q).join(", ")})`).join(",\n")}
),
missing as (
  select e.* from expected e
  where (e.kind = 'table' and not exists (select 1 from information_schema.tables t where t.table_schema = 'public' and t.table_name = e.name))
     or (e.kind = 'function' and not exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname = 'public' and p.proname = e.name))
     or (e.kind = 'column' and not exists (select 1 from information_schema.columns c where c.table_schema = 'public' and c.table_name = e.name and c.column_name = e.extra))
)
select mig as "migration", kind, name, extra as "column" from missing
union all
select '—', 'ok', 'Everything is in place (' || (select count(*) from expected) || ' objects checked).', null where not exists (select 1 from missing)
order by 1, 2, 3;
`;
fs.writeFileSync("supabase/check_setup.sql", out);
console.log(`check_setup.sql: ${rows.length} objects from ${files.length} migrations`);
