// Generates supabase/migrations/0002_catalog.sql from src/lib/catalog.json (the single source of truth).
// Run: node scripts/gen-catalog.mjs
import fs from "node:fs";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("..", import.meta.url));
const cat = JSON.parse(fs.readFileSync(root + "src/lib/catalog.json", "utf8"));
const q = (s) => (s === null || s === undefined ? "null" : `'${String(s).replace(/'/g, "''")}'`);

const perms = [];
cat.modules.forEach((m) => m.submodules.forEach((s) => s.actions.forEach((a) => perms.push({ key: `${m.code}.${s.code}.${a}`, sub: `${m.code}.${s.code}`, module: m.code, action: a }))));
const subOf = new Map(cat.modules.flatMap((m) => m.submodules.map((s) => [`${m.code}.${s.code}`, s])));

const grants = [];
const errors = [];
for (const r of cat.roles) {
  for (const [k, v] of Object.entries(r.grants)) {
    if (k === "*") { perms.forEach((p) => grants.push([r.code, p.key, v])); continue; }
    const sub = subOf.get(k);
    if (!sub) { errors.push(`${r.code}: unknown sub-module ${k}`); continue; }
    const [scope, ...acts] = v;
    if (!cat.scopes[scope]) errors.push(`${r.code}.${k}: unknown scope ${scope}`);
    const list = acts.includes("*") ? sub.actions : acts;
    for (const a of list) {
      if (!sub.actions.includes(a)) { errors.push(`${r.code}: ${k} has no action ${a}`); continue; }
      grants.push([r.code, `${k}.${a}`, scope]);
    }
  }
}
if (errors.length) { console.error(errors.join("\n")); process.exit(1); }

let sql = `-- GENERATED by scripts/gen-catalog.mjs from src/lib/catalog.json — do not edit by hand.
-- Module map: modules → sub-modules → permissions (module.submodule.action) + default role templates.

create table if not exists public.erp_modules (
  code text primary key, name text not null, grp text not null, tier text not null, core boolean not null default false, sort int not null default 0
);
create table if not exists public.erp_submodules (
  code text primary key, module_code text not null references public.erp_modules(code) on delete cascade,
  name text not null, built boolean not null default false, sort int not null default 0
);
create table if not exists public.erp_permissions (
  key text primary key, submodule_code text not null references public.erp_submodules(code) on delete cascade,
  module_code text not null references public.erp_modules(code) on delete cascade, action text not null
);
create table if not exists public.role_templates (
  code text primary key, name text not null, kind text not null check (kind in ('staff','family')),
  description text, locked boolean not null default false, sort int not null default 0
);
create table if not exists public.role_template_permissions (
  template_code text not null references public.role_templates(code) on delete cascade,
  perm_key text not null references public.erp_permissions(key) on delete cascade,
  scope text not null check (scope in ('school','assigned','own','child','self')),
  primary key (template_code, perm_key)
);

`;
sql += `insert into public.erp_modules (code, name, grp, tier, core, sort) values\n` +
  cat.modules.map((m, i) => `  (${q(m.code)}, ${q(m.name)}, ${q(m.group)}, ${q(m.tier)}, ${m.core ? "true" : "false"}, ${i})`).join(",\n") +
  `\non conflict (code) do update set name = excluded.name, grp = excluded.grp, tier = excluded.tier, core = excluded.core, sort = excluded.sort;\n\n`;
sql += `insert into public.erp_submodules (code, module_code, name, built, sort) values\n` +
  cat.modules.flatMap((m) => m.submodules.map((s, i) => `  (${q(`${m.code}.${s.code}`)}, ${q(m.code)}, ${q(s.name)}, ${s.built ? "true" : "false"}, ${i})`)).join(",\n") +
  `\non conflict (code) do update set name = excluded.name, built = excluded.built, sort = excluded.sort;\n\n`;
sql += `insert into public.erp_permissions (key, submodule_code, module_code, action) values\n` +
  perms.map((p) => `  (${q(p.key)}, ${q(p.sub)}, ${q(p.module)}, ${q(p.action)})`).join(",\n") +
  `\non conflict (key) do nothing;\n`;
sql += `delete from public.erp_permissions where key not in (${perms.map((p) => q(p.key)).join(", ")});\n`;
sql += `delete from public.erp_submodules where code not in (${[...subOf.keys()].map(q).join(", ")});\n\n`;
sql += `insert into public.role_templates (code, name, kind, description, locked, sort) values\n` +
  cat.roles.map((r, i) => `  (${q(r.code)}, ${q(r.name)}, ${q(r.kind)}, ${q(r.description)}, ${r.locked ? "true" : "false"}, ${i})`).join(",\n") +
  `\non conflict (code) do update set name = excluded.name, kind = excluded.kind, description = excluded.description, locked = excluded.locked, sort = excluded.sort;\n\n`;
sql += `delete from public.role_template_permissions;\ninsert into public.role_template_permissions (template_code, perm_key, scope) values\n` +
  grants.map(([r, k, s]) => `  (${q(r)}, ${q(k)}, ${q(s)})`).join(",\n") + `;\n`;

fs.writeFileSync(root + "supabase/migrations/0002_catalog.sql", sql);
console.log(`modules ${cat.modules.length}, sub-modules ${subOf.size}, permissions ${perms.length}, roles ${cat.roles.length}, grants ${grants.length}`);
